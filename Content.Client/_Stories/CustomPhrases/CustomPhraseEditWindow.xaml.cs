using Content.Client.UserInterface.Controls;
using Content.Client.UserInterface.Systems.Chat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Stories.CustomPhrases;

[GenerateTypedNameReferences]
public sealed partial class CustomPhraseEditWindow : FancyWindow
{
    private readonly CustomPhrasesUIController _controller;

    public CustomPhrase? Phrase { get; }

    public CustomPhraseEditWindow(CustomPhrasesUIController controller, CustomPhrase? phrase)
    {
        RobustXamlLoader.Load(this);
        _controller = controller;
        Phrase = phrase;

        if (phrase != null)
        {
            TextEdit.Text = phrase.Text;
            TagsEdit.Text = CustomPhrasesUIController.FormatTags(phrase.Tags);
        }

        TextEdit.OnTextEntered += _ => Submit();
        TagsEdit.OnTextEntered += _ => Submit();
        SaveButton.OnPressed += _ => Submit();
        CancelButton.OnPressed += _ => Close();

        TextEdit.GrabKeyboardFocus();
    }

    private void Submit()
    {
        var text = TextEdit.Text.Trim();
        if (text.Length == 0)
        {
            ShowError(Loc.GetString("stories-custom-phrases-error-empty"));
            return;
        }

        var maxLength = IoCManager.Resolve<IUserInterfaceManager>().GetUIController<ChatUIController>().MaxMessageLength;
        if (text.Length > maxLength)
        {
            ShowError(Loc.GetString("stories-custom-phrases-error-too-long", ("max", maxLength)));
            return;
        }

        var tags = CustomPhrasesUIController.ParseTags(TagsEdit.Text);

        if (Phrase != null)
        {
            _controller.Update(Phrase, text, tags);
        }
        else if (!_controller.TryAdd(text, tags))
        {
            ShowError(Loc.GetString("stories-custom-phrases-error-limit", ("max", CustomPhrasesUIController.MaxPhrases)));
            return;
        }

        Close();
    }

    private void ShowError(string message)
    {
        ErrorLabel.Text = message;
        ErrorLabel.Visible = true;
    }
}
