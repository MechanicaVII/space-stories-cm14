using System.Linq;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Stories.CustomPhrases;

[GenerateTypedNameReferences]
public sealed partial class CustomPhrasesWindow : FancyWindow
{
    private const int PreviewLength = 160;
    private const string EditIcon = "/Textures/Interface/pencil.png";

    private readonly CustomPhrasesUIController _controller;
    private readonly List<ContainerButton> _sendButtons = new();
    private CustomPhraseEditWindow? _editWindow;
    private string? _selectedTag;
    private bool _coolingDown;

    public CustomPhrasesWindow(CustomPhrasesUIController controller)
    {
        RobustXamlLoader.Load(this);
        _controller = controller;

        SearchBar.OnTextChanged += _ => RefreshPhrases();
        AddButton.OnPressed += _ => OpenEditor(null);

        _controller.PhrasesChanged += Refresh;
        OnClose += () =>
        {
            _controller.PhrasesChanged -= Refresh;
            _editWindow?.Close();
        };

        Refresh();
        UpdateCooldown();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateCooldown();
    }

    private void UpdateCooldown()
    {
        var progress = _controller.CooldownProgress;
        CooldownBar.Value = progress;
        CooldownBar.Modulate = progress > 0 ? Color.White : Color.Transparent;

        var coolingDown = progress > 0;
        if (coolingDown == _coolingDown)
            return;

        _coolingDown = coolingDown;
        PhrasesContainer.Modulate = coolingDown ? Color.White.WithAlpha(0.5f) : Color.White;

        foreach (var button in _sendButtons)
        {
            button.Disabled = coolingDown;
        }
    }

    private void Refresh()
    {
        RefreshTags();
        RefreshPhrases();
    }

    private void RefreshTags()
    {
        TagsContainer.RemoveAllChildren();

        var tags = _controller.AllTags();

        if (_selectedTag != null && !tags.Contains(_selectedTag))
            _selectedTag = null;

        TagsContainer.Visible = tags.Count > 0;

        var group = new ButtonGroup(false);
        AddTagButton(Loc.GetString("stories-custom-phrases-tag-all"), null, group);

        foreach (var tag in tags)
        {
            AddTagButton($"#{tag}", tag, group);
        }
    }

    private void AddTagButton(string text, string? tag, ButtonGroup group)
    {
        var button = new Button
        {
            Text = text,
            ToggleMode = true,
            Group = group,
            StyleClasses = { StyleBase.ButtonOpenBoth },
        };

        button.Pressed = _selectedTag == tag;
        button.OnPressed += _ =>
        {
            _selectedTag = tag;
            RefreshPhrases();
        };

        TagsContainer.AddChild(button);
    }

    private void RefreshPhrases()
    {
        PhrasesContainer.RemoveAllChildren();
        _sendButtons.Clear();

        var search = SearchBar.Text.Trim();
        var searchTag = search.TrimStart('#');
        var shown = 0;

        foreach (var phrase in _controller.Phrases)
        {
            if (_selectedTag != null && !phrase.Tags.Contains(_selectedTag))
                continue;

            if (search.Length > 0 &&
                !phrase.Text.Contains(search, StringComparison.OrdinalIgnoreCase) &&
                (searchTag.Length == 0 || !phrase.Tags.Any(t => t.Contains(searchTag, StringComparison.OrdinalIgnoreCase))))
            {
                continue;
            }

            PhrasesContainer.AddChild(CreateRow(phrase));
            shown++;
        }

        EmptyLabel.Text = Loc.GetString(_controller.Phrases.Count == 0
            ? "stories-custom-phrases-empty"
            : "stories-custom-phrases-not-found");
        EmptyLabel.Visible = shown == 0;
    }

    private Control CreateRow(CustomPhrase phrase)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 4,
        };

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(6, 3),
        };

        var preview = phrase.Text.Length > PreviewLength
            ? phrase.Text[..PreviewLength].TrimEnd() + "..."
            : phrase.Text;

        var text = new RichTextLabel { HorizontalExpand = true };
        text.SetMessage(FormattedMessage.FromUnformatted(preview));
        content.AddChild(text);

        if (phrase.Tags.Count > 0)
        {
            content.AddChild(new Label
            {
                Text = CustomPhrasesUIController.FormatTags(phrase.Tags),
                ClipText = true,
                HorizontalExpand = true,
                StyleClasses = { StyleBase.StyleClassLabelSubText },
            });
        }

        var sendButton = new ContainerButton
        {
            HorizontalExpand = true,
            StyleClasses = { ContainerButton.StyleClassButton },
            Disabled = _coolingDown,
        };
        sendButton.AddChild(content);
        sendButton.OnPressed += _ => _controller.Send(phrase);
        _sendButtons.Add(sendButton);

        var editButton = new TextureButton
        {
            TexturePath = EditIcon,
            VerticalAlignment = VAlignment.Center,
            Margin = new Thickness(2, 0),
            ToolTip = Loc.GetString("stories-custom-phrases-edit"),
        };
        editButton.OnPressed += _ => OpenEditor(phrase);

        row.AddChild(sendButton);
        row.AddChild(editButton);
        return row;
    }

    private void OpenEditor(CustomPhrase? phrase)
    {
        _editWindow?.Close();

        _editWindow = new CustomPhraseEditWindow(_controller, phrase);
        _editWindow.OnClose += () => _editWindow = null;
        _editWindow.OpenCentered();
    }
}
